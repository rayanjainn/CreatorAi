import { expect, type APIRequestContext, type Locator, type Page } from '@playwright/test'

export const API = process.env.E2E_API_URL || 'http://localhost:8100'
/** The seeded demo account; E2E_EMAIL / E2E_PASSWORD point the specs at another account (a real dev stack). */
export const DEMO = { email: process.env.E2E_EMAIL || 'demo@creatorai.local', password: process.env.E2E_PASSWORD || 'demo1234' }

export async function login(page: Page) {
  await page.goto('/login')
  await page.fill('#email', DEMO.email)
  await page.fill('#password', DEMO.password)
  await page.click('[data-testid=login-submit]')
  await page.waitForURL('**/dashboard')
}

export async function apiToken(request: APIRequestContext): Promise<string> {
  const res = await request.post(`${API}/api/v1/auth/login`, { data: DEMO })
  expect(res.ok()).toBeTruthy()
  return (await res.json()).access_token
}

export type ApiCard = { id: string; title: string; stage: string; position: number }

export async function apiBoard(request: APIRequestContext): Promise<{ stage: string; cards: ApiCard[] }[]> {
  const token = await apiToken(request)
  const res = await request.get(`${API}/api/v1/content/board`, { headers: { Authorization: `Bearer ${token}` } })
  return (await res.json()).columns
}

export async function apiFindCard(request: APIRequestContext, title: string): Promise<ApiCard | undefined> {
  const cols = await apiBoard(request)
  return cols.flatMap((c) => c.cards).find((c) => c.title.includes(title))
}

/** Native HTML5 drag & drop needs several intermediate mouse moves (locator.dragTo emits too few). */
export async function dragTo(page: Page, source: Locator, target: Locator) {
  const s = (await source.boundingBox())!
  const t = (await target.boundingBox())!
  await page.mouse.move(s.x + 40, s.y + 30)
  await page.mouse.down()
  await page.mouse.move(s.x + 60, s.y + 50, { steps: 5 })
  await page.mouse.move(t.x + 50, t.y + 40, { steps: 10 })
  await page.mouse.move(t.x + 52, t.y + 42, { steps: 3 })
  await page.mouse.up()
}

/* ---------- API helpers for the project and library specs ---------- */
import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, copyFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

export async function authHeaders(request: APIRequestContext): Promise<{ Authorization: string }> {
  return { Authorization: `Bearer ${await apiToken(request)}` }
}

/** The seeded hero project (stage edit, script, plan, matches, 2 demo clips, one demo asset). */
export async function heroId(request: APIRequestContext): Promise<string> {
  const card = await apiFindCard(request, 'My whole editing workflow')
  if (!card) throw new Error('hero project not found: was the DB seeded?')
  return card.id
}

export async function createItem(request: APIRequestContext, title: string, extra: Record<string, unknown> = {}): Promise<string> {
  const res = await request.post(`${API}/api/v1/content`, { headers: await authHeaders(request), data: { title, ...extra } })
  expect(res.ok()).toBeTruthy()
  return (await res.json()).id
}

export async function apiGet<T = unknown>(request: APIRequestContext, path: string): Promise<T> {
  const res = await request.get(`${API}/api/v1${path}`, { headers: await authHeaders(request) })
  expect(res.ok(), `${path} -> ${res.status()}`).toBeTruthy()
  return (await res.json()) as T
}

/**
 * A small playable clip with a transcript, generated by backend/scripts/make_demo_media.py (synthetic, labelled DEMO).
 * `unique` stamps a metadata comment so the sha256 differs and the upload is not deduplicated.
 */
export function makeDemoClip(unique: string): { video: string; words: string } {
  const root = resolve(__dirname, '..', '..')
  const py = process.env.E2E_BACKEND_PYTHON || join(root, 'backend', '.venv', 'bin', 'python')
  const base = join(tmpdir(), 'creatorai-e2e-media')
  mkdirSync(base, { recursive: true })
  if (!existsSync(join(base, 'hero_demo.mp4'))) {
    execFileSync(py, [join(root, 'backend', 'scripts', 'make_demo_media.py'), '--out', base], { stdio: 'ignore' })
  }
  const video = join(base, `clip-${unique}.mp4`)
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', join(base, 'hero_demo.mp4'), '-c', 'copy', '-metadata', `comment=${unique}`, video])
  const words = join(base, `clip-${unique}.words.json`)
  copyFileSync(join(base, 'hero_demo.words.json'), words)
  return { video, words }
}
