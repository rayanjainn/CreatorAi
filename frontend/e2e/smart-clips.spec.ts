import { expect, test } from '@playwright/test'
import { API, apiGet, authHeaders, login } from './helpers'

/**
 * The optional cloud clipper (LumiClip) through the real API, with `scripts/fake_lumiclip.py` standing in for the provider
 * (no network, no key). Covers: a project runs through the pipeline to three clips, preview, saving a clip to the library,
 * the "needs a login" failure, out-of-credits, the library-source gating without Cloudinary, and the setup card.
 */
test.describe.configure({ mode: 'serial' })

const LINK = 'https://www.youtube.com/watch?v=abcdefghijk'

test('a link goes through the pipeline to three clips, previews, and saves to the library', async ({ page, request }) => {
  await login(page)
  await page.goto('/smart-clips?tab=link')
  await expect(page.getByTestId('lumiclip-form')).toBeVisible()
  await expect(page.getByTestId('lumiclip-start')).toBeDisabled() // no link yet

  await page.getByTestId('lumiclip-url').fill('not a link')
  await expect(page.getByTestId('lumiclip-start')).toBeDisabled()
  await page.getByTestId('lumiclip-url').fill(LINK)
  // a bad time range is explained and blocks the button
  await page.locator('#sc-start').fill('2:00')
  await page.locator('#sc-end').fill('1:00')
  await expect(page.getByText('End must be after the start')).toBeVisible()
  await expect(page.getByTestId('lumiclip-start')).toBeDisabled()
  await page.locator('#sc-end').fill('')
  await page.getByRole('radio', { name: /Spot/ }).click()
  await page.getByTestId('lumiclip-start').click()

  await expect(page.getByTestId('lumiclip-progress')).toBeVisible()
  await expect(page.getByTestId('lumiclip-clip')).toHaveCount(3, { timeout: 45_000 })
  await expect(page.getByTestId('lumiclip-project')).toHaveAttribute('data-status', 'completed')
  await expect(page.getByTestId('lumiclip-clips').first()).toContainText('The one thing nobody tells you')
  // the "Recent" list follows the project (it must not keep saying "Working…")
  await expect(page.getByTestId('lumiclip-projects')).toContainText('3 clips')
  // generated by an outside service: it says so
  await expect(page.getByTestId('lumiclip-clip').first().locator('.prov[data-source=ai]')).toBeVisible()

  // what we sent to the provider (options, no key in the browser)
  const projects = await apiGet<{ options: Record<string, unknown>; aspect_ratio: string }[]>(request, '/lumiclip/projects')
  expect(projects[0].options).toMatchObject({ subtitle_style: 'spot', start_time: 120 })

  // preview opens a player
  await page.getByTestId('lumiclip-clip').first().locator('.sc-clip-thumb').click()
  await expect(page.locator('.sc-preview video')).toBeVisible()
  await page.keyboard.press('Escape')

  // save to the library: the clip becomes a normal asset (light mode, no AI key needed)
  await page.getByTestId('lumiclip-clip').first().getByTestId('clip-save').click()
  await expect(page.getByTestId('lumiclip-clip').first().getByTestId('clip-saved')).toBeVisible({ timeout: 30_000 })
  const assets = (await apiGet<{ items: { id: string; filename: string; kind: string; status: string }[] }>(request, '/assets?limit=100')).items
  const saved = assets.find((a) => a.filename.includes('(lumiclip)'))
  expect(saved).toBeTruthy()
  expect(saved!.kind).toBe('video')
  const detail = await apiGet<{ analysis: { mode?: string }; status: string }>(request, `/assets/${saved!.id}`)
  expect(detail.analysis.mode).toBe('light')
  await expect.poll(async () => (await apiGet<{ status: string }>(request, `/assets/${saved!.id}`)).status, { timeout: 30_000 }).toBe('ready')
  // remove what this test created: the library spec expects only the hero asset
  await request.delete(`${API}/api/v1/assets/${saved!.id}`, { headers: await authHeaders(request) })
  const list = await apiGet<{ id: string }[]>(request, '/lumiclip/projects')
  for (const p of list) await request.delete(`${API}/api/v1/lumiclip/projects/${p.id}`, { headers: await authHeaders(request) })
})

test('a video that needs a login fails with advice, not a stack trace', async ({ page, request }) => {
  await login(page)
  await page.goto('/smart-clips?tab=link')
  await page.getByTestId('lumiclip-url').fill('https://www.youtube.com/watch?v=private-video')
  await page.getByTestId('lumiclip-start').click()
  const fail = page.getByTestId('lumiclip-failed')
  await expect(fail).toBeVisible({ timeout: 45_000 })
  await expect(fail).toHaveAttribute('data-category', 'source_auth')
  await expect(fail).toContainText('needs a login')
  await expect(page.getByTestId('lumiclip-projects')).toContainText('Failed')
  for (const p of await apiGet<{ id: string }[]>(request, '/lumiclip/projects')) await request.delete(`${API}/api/v1/lumiclip/projects/${p.id}`, { headers: await authHeaders(request) })
})

test('out of credits is shown inline on the form', async ({ page }) => {
  await login(page)
  await page.goto('/smart-clips?tab=link')
  await page.getByTestId('lumiclip-url').fill('https://www.youtube.com/watch?v=quota-video')
  await page.getByTestId('lumiclip-start').click()
  await expect(page.getByTestId('lumiclip-start-error')).toContainText('out of credits')
})

test('a library video needs Cloudinary: the form says so and does not call anything', async ({ page }) => {
  await login(page)
  await page.goto('/smart-clips?tab=link')
  await page.getByRole('button', { name: 'My library' }).click()
  await expect(page.getByText('CLOUDINARY_CLOUD_NAME')).toBeVisible()
  await expect(page.getByTestId('lumiclip-start')).toBeDisabled()
})

test('without a LumiClip key the page shows an honest setup card instead of the form', async ({ page }) => {
  await login(page)
  await page.route('**/api/v1/lumiclip/status', (route) => route.fulfill({ json: { configured: false, cloudinary_configured: false, base_url: 'https://api.lumiclip.ai' } }))
  await page.goto('/smart-clips?tab=link')
  await expect(page.getByTestId('lumiclip-setup')).toContainText('LUMICLIP_API_KEY')
  await expect(page.getByTestId('lumiclip-form')).toHaveCount(0)
  // the tab for your own projects still works without it
  await page.getByRole('button', { name: 'Your projects' }).click()
  await expect(page).toHaveURL(/\/smart-clips$/)
})
