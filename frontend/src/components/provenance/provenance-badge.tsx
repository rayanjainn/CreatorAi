'use client'

import { Sparkles, FlaskConical, Calculator, Beaker, UserRound } from 'lucide-react'
import { Tooltip } from '@/components/ui/tooltip'
import type { Provenance, ProvenanceSource } from '@/lib/api/types'

const META: Record<ProvenanceSource, { label: string; title: string; text: string; Icon: typeof Sparkles }> = {
  ai: {
    label: 'AI',
    title: 'Generated by an AI model',
    text: 'A real model produced this. Review it before you rely on it.',
    Icon: Sparkles,
  },
  mock: {
    label: 'Mock',
    title: 'Mock output, not real AI',
    text: 'A deterministic offline stand-in produced this (LLM_ALLOW_MOCK=true). Do not publish it.',
    Icon: FlaskConical,
  },
  heuristic: {
    label: 'Heuristic',
    title: 'Rule-based estimate',
    text: 'Computed by rules or a fallback algorithm, not a language model. Treat it as a rough guide.',
    Icon: Calculator,
  },
  demo: {
    label: 'Demo',
    title: 'Demo data',
    text: 'Seeded sample content from `make seed`. It is not your real data.',
    Icon: Beaker,
  },
  user: {
    label: 'You',
    title: 'Written by you',
    text: 'You typed or edited this yourself.',
    Icon: UserRound,
  },
}

export const PROVENANCE_SOURCES = Object.keys(META) as ProvenanceSource[]

export type ProvenanceBadgeProps = Partial<Provenance> & {
  /** Override the visible label. */
  label?: string
  /** Hide the text and show the icon only. */
  iconOnly?: boolean
  className?: string
}

/**
 * Marks generated content with where it came from. Use it on EVERY surface that shows a model, mock,
 * heuristic, seeded or user-authored result. The tooltip names the provider/model when known.
 * Backend contract: docs/BACKEND_FOUNDATION.md (provenance), `{source, provider, model}`.
 */
export function ProvenanceBadge({ source = 'ai', provider, model, label, iconOnly, className }: ProvenanceBadgeProps) {
  const meta = META[source] ?? META.ai
  const { Icon } = meta
  const text = label ?? meta.label
  return (
    <Tooltip
      content={
        <div>
          <b>{meta.title}</b>
          <div style={{ marginTop: 3 }}>{meta.text}</div>
          {(provider || model) && (
            <dl>
              {provider && (
                <>
                  <dt>Provider</dt>
                  <dd>{provider}</dd>
                </>
              )}
              {model && (
                <>
                  <dt>Model</dt>
                  <dd>{model}</dd>
                </>
              )}
            </dl>
          )}
        </div>
      }
    >
      <span
        className={`prov ${className ?? ''}`}
        data-source={source}
        tabIndex={0}
        aria-label={`${meta.title}${provider ? `, provider ${provider}` : ''}${model ? `, model ${model}` : ''}`}
      >
        <Icon aria-hidden />
        {!iconOnly && text}
      </span>
    </Tooltip>
  )
}
